#pragma once

typedef enum mutableStringStatus {
	MS_NULL = -1,				// mutableString 实例为 NULL
	MS_AVAILABLE = 0,			// 实例可用
	MS_NULLBUFFER = 1,			// 实例的 buffer 为 NULL
	MS_EMPTY,					// mutableString 空串
	MS_BLANK,					// mutableString 全空白

	MS_FAILEDTOCOMBINE,			// 内容结合失败
	MS_WRONGSTATUS,				// mutableString 状态非可用
	MS_FAILEDTOREALLOC,			// 重分配内存失败
	MS_FAILEDTOALLOC,			// 内存操作失败

	MS_NULLINT,
	MS_OVERFLOWINT,
	MS_NOTINT,
	MS_SUCCEEDTOINT,

	MS_NULLLONG,
	MS_OVERFLOWLONG,
	MS_NOTLONG,
	MS_SUCCEEDTOLONG,

	MS_NULLLONGLONG,
	MS_OVERFLOWLONGLONG,
	MS_NOTLONGLONG,
	MS_SUCCEEDTOLONGLONG,

	MS_NULLFLOAT,
	MS_OVERFLOWFLOAT,
	MS_NOTFLOAT,
	MS_SUCCEEDTOFLOAT,

	MS_NULLDOUBLE,
	MS_OVERFLOWDOUBLE,
	MS_NOTDOUBLE,
	MS_SUCCEEDTODOUBLE,

	MS_NULLCHAR,				// 无效的待接受 char*
	MS_NULLARRAY,				// 输出数组指针为 NULL
	MS_NULLCOUNT,				// 计数器指针为 NULL
	MS_NULLTARGET,				// target 指针为 NULL
	MS_NULLRECEIVER,

	MS_IDXOUTBOUNDS,			// 索引越界
	MS_SUCCESSFULIDX,			// 索引有效
	MS_SUCCEEDTOTRUNCATE,		// 成功截断 mutableString
	MS_SUCCEEDTOFINDCH,			// 成功通过 ch 找到索引
	MS_WITHOUTCH,				// 没有通过 ch 找到索引
	MS_INVALIDSTART,			// 起始点索引无效
	MS_INVALIDEND,				// 结束点索引无效
	MS_INVALIDIDX,				// 索引无效
	MS_INVALIDREPLACEMENT,		// 替换内容无效
	MS_LENOUTOFTYPEMAX,
	MS_INVALIDSRC,
	MS_INVALIDCHFORCHANGE,

	MS_SUCCESSFULOP,			// 操作成功
	MS_PARTIALSPLIT,			// 分割部分成功（数组中有 NULL）
	MS_NOTARGETMATCHED,			// target 未匹配到
}mutableStringStatus;